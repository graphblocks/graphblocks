class DocsCheckError(RuntimeError):
    """The documentation tree or checker contract is unsafe or malformed."""


class _UniqueKeyLoader(yaml.SafeLoader):
    pass


class _ReferenceProbe(dict[str, object]):
    def get(self, key: object, default: object = None) -> object:
        if type(key) is not str:
            return default
        if key in self:
            return super().get(key, default)
        return {
            "href": UNRESOLVED_REFERENCE_PREFIX + quote(key, safe=""),
            "title": "",
        }


class _HtmlScanner(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.attributes: list[tuple[int, str, str, str]] = []
        self.comments: list[tuple[int, str]] = []

    def _record_attributes(
        self,
        tag: str,
        attrs: list[tuple[str, str | None]],
    ) -> None:
        line = self.getpos()[0]
        self.attributes.extend(
            (line, tag.casefold(), name.casefold(), value)
            for name, value in attrs
            if value is not None
        )

    def handle_starttag(
        self,
        tag: str,
        attrs: list[tuple[str, str | None]],
    ) -> None:
        self._record_attributes(tag, attrs)

    def handle_startendtag(
        self,
        tag: str,
        attrs: list[tuple[str, str | None]],
    ) -> None:
        self._record_attributes(tag, attrs)

    def handle_comment(self, data: str) -> None:
        self.comments.append((self.getpos()[0], data))


def _record_reference_rule(
    state: StateInline,
    silent: bool,
    *,
    image: bool,
) -> bool:
    start = state.pos
    label_start = start + (2 if image else 1)
    label_end = state.md.helpers.parseLinkLabel(
        state,
        start + (1 if image else 0),
        not image,
    )
    explicit = label_end >= 0 and (
        label_end + 1 < state.posMax and state.src[label_end + 1] == "["
    )
    previous_token_count = len(state.tokens)
    matched = _parse_image(state, silent) if image else _parse_link(state, silent)
    if (
        not matched
        or silent
        or state.src != state.env.get(REFERENCE_PROBE_ROOT)
        or label_end < label_start
    ):
        return matched
    token_type = "image" if image else "link_open"
    attribute = "src" if image else "href"
    for token in state.tokens[previous_token_count:]:
        if token.type != token_type:
            continue
        target = token.attrGet(attribute)
        if target and target.startswith(UNRESOLVED_REFERENCE_PREFIX):
            records = state.env.get(REFERENCE_PROBE_RECORDS)
            if isinstance(records, list):
                records.append(
                    (
                        start,
                        unquote(target.removeprefix(UNRESOLVED_REFERENCE_PREFIX)),
                        state.src[label_start:label_end],
                        not explicit,
                        image,
                    )
                )
            break
    return matched


def _record_link_reference(state: StateInline, silent: bool) -> bool:
    return _record_reference_rule(state, silent, image=False)


def _record_image_reference(state: StateInline, silent: bool) -> bool:
    return _record_reference_rule(state, silent, image=True)


def _construct_unique_mapping(
    loader: _UniqueKeyLoader,
    node: yaml.nodes.MappingNode,
    deep: bool = False,
) -> dict[object, object]:
    mapping: dict[object, object] = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        try:
            duplicate = key in mapping
        except TypeError as error:
            raise DocsCheckError(
                "generated-documentation registry keys must be scalar"
            ) from error
        if duplicate:
            raise DocsCheckError(
                f"generated-documentation registry repeats YAML key {key!r}"
            )
        mapping[key] = loader.construct_object(value_node, deep=deep)
    return mapping


_UniqueKeyLoader.add_constructor(
    yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG,
    _construct_unique_mapping,
)


